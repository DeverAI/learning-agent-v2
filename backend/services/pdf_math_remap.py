_PUA_RE = re.compile(r"[\uF020-\uF0FF]")


def remap_symbol_pua(text: str) -> str:
    """把 Adobe Symbol PUA 码点映射为可读 Unicode。未知码点保留原样。"""
    if not text:
        return text
    def _sub(m: re.Match) -> str:
        cp = ord(m.group(0))
        return _SYMBOL_MAP.get(cp, m.group(0))
    return _PUA_RE.sub(_sub, text)


def count_pua(text: str) -> int:
    if not text:
        return 0
    return sum(1 for ch in text if "\uf020" <= ch <= "\uf0ff")
