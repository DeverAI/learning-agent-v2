  // 根据 SVG viewBox 自动将图缩放并居中到视口（响应式适配）
  function _sgFitToViewport(){
    var container = document.querySelector('.sg-viewport');
    var inner = document.querySelector('.sg-inner');
    var svg = inner ? inner.querySelector('svg') : null;
    if(!container || !inner || !svg) return;
    var rect = container.getBoundingClientRect();
    var cw = rect.width, ch = rect.height;
    if(!cw || !ch) return; // 零尺寸或隐藏容器
    var vb = svg.getAttribute('viewBox');
    if(!vb){ _sgScale=1; _sgX=0; _sgY=0; applySGTransform(); return; }
    var parts = vb.trim().replace(/,/g,' ').split(/\s+/).filter(function(v){return v!==''});
    if(parts.length !== 4){ _sgScale=1; _sgX=0; _sgY=0; applySGTransform(); console.warn('[SG] invalid viewBox'); return; }
    var minX = parseFloat(parts[0]), minY = parseFloat(parts[1]);
    var vw = parseFloat(parts[2]), vh = parseFloat(parts[3]);
    if(!isFinite(minX) || !isFinite(minY) || !isFinite(vw) || !isFinite(vh) || vw <= 0 || vh <= 0){
      _sgScale=1; _sgX=0; _sgY=0; applySGTransform(); console.warn('[SG] invalid viewBox dimensions'); return;
    }
    _sgAdaptCardHeight(vw,vh);
    rect = container.getBoundingClientRect();
    cw = rect.width; ch = rect.height;
    var pad = 0.9;
    var scale = Math.min(cw / vw, ch / vh) * pad;
    scale = _sgClampScale(scale);
    _sgScale = scale;
    // SVG 自身已经按 viewBox 的 minX/minY 映射内部坐标；外层 CSS transform
    // 只需居中 SVG 的可视盒，不能再次扣除原点，否则会把整张图推向右下角。
    _sgX = (cw - vw * scale) / 2;
    _sgY = (ch - vh * scale) / 2;
    applySGTransform();
  }
  function _sgAttachResize(){
    if(_sgResizeObserver || _sgResizeFallback) return; // 已挂载，避免重复
    var debouncedFit = function(){
      if(_sgResizeTimer) clearTimeout(_sgResizeTimer);
      _sgResizeTimer = setTimeout(function(){
        _sgResizeTimer = null;
        _sgFitToViewport();
      }, 100);
    };
    if(typeof ResizeObserver !== 'undefined'){
      _sgResizeObserver = new ResizeObserver(function(entries){ debouncedFit(); });
      var container = document.querySelector('.sg-viewport');
      if(container) _sgResizeObserver.observe(container);
    }else{
      _sgResizeFallback = debouncedFit;
      window.addEventListener('resize', _sgResizeFallback);
    }
  }
