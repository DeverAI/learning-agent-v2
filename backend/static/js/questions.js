  function _cmpHexAlpha(color, alphaHex){
    if(!color || color[0]!=='#') return 'color-mix(in srgb,'+color+' 14%,transparent)';
    // 统一转为6位hex再追加alpha
    var c=color.toLowerCase().replace('#','');
    if(c.length===3) c=c.split('').map(function(ch){return ch+ch;}).join('');
    if(c.length!==6) return color;
    return '#'+c+(alphaHex||'22');
  }
  function _cmpRegionColor(index){
    var strengths=[100,82,66,50];
    var strength=strengths[index%strengths.length];
    return strength===100?'var(--accent)':'color-mix(in srgb,var(--accent) '+strength+'%,var(--text))';
  }
  function _cmpApplyRegionColors(regions, isDark, nodes){
    var svg=document.querySelector('#cmpInner svg');
    if(!svg) return;
    var rects=svg.querySelectorAll('rect[data-node-id]');
    rects.forEach(function(rect){
      var nid=parseInt(rect.getAttribute('data-node-id'));
      if(isNaN(nid)) return;
      rect.style.cursor='pointer';
      rect.addEventListener('click', function(){ cmpHighlightRegionByNode(nid); });
    });
    regions.forEach(function(region,regionIndex){
      var color=_cmpRegionColor(regionIndex);
      var fillColor=_cmpHexAlpha(color,'22');
      (region.node_ids||[]).forEach(function(nid){
        var rect=svg.querySelector('rect[data-node-id="'+nid+'"]');
        if(rect){
          rect.style.stroke=color;
          rect.style.strokeWidth='3';
          rect.style.fill=fillColor;
          rect.setAttribute('data-region-id', region.id);
        }
      });
    });
  }
  function _cmpNormalizeAnswerBlocks(container){
    var blockTags=['P','DIV','H1','H2','H3','H4','H5','H6','UL','OL','PRE','BLOCKQUOTE','TABLE','SECTION','ARTICLE'];
    var children=Array.from(container.childNodes);
    var frag=document.createDocumentFragment();
    var currentWrap=null;
    function flushWrap(){
      if(currentWrap && currentWrap.childNodes.length){
        frag.appendChild(currentWrap);
        currentWrap=null;
      }
    }
    children.forEach(function(node){
      if(node.nodeType===Node.ELEMENT_NODE && blockTags.indexOf(node.tagName)!==-1){
        flushWrap();
        frag.appendChild(node);
        return;
      }
      if(node.nodeType===Node.TEXT_NODE && !node.textContent.trim()) return;
      if(!currentWrap){
        currentWrap=document.createElement('div');
        currentWrap.className='cmp-answer-wrap';
      }
      currentWrap.appendChild(node);
    });
    flushWrap();
    container.innerHTML='';
    container.appendChild(frag);
  }
  function cmpHighlightRegionByNode(nid){
    var region=null;
    (_cmpState.regions||[]).forEach(function(r){
      if((r.node_ids||[]).indexOf(nid)!==-1 && !region) region=r;
    });
    if(!region) return;
    var range=region.paragraph_range||[0,0];
    var start=Math.max(0,parseInt(range[0])||0);
    var blocks=_cmpState.answerBlocks;
    if(start>=blocks.length) return;
    blocks[start].scrollIntoView({behavior:'smooth',block:'start'});
    // 临时高亮闪烁
    blocks[start].style.transition='box-shadow .2s';
    var regionIndex=(_cmpState.regions||[]).indexOf(region);
    blocks[start].style.boxShadow='0 0 0 3px '+_cmpRegionColor(Math.max(0,regionIndex));
    setTimeout(function(){blocks[start].style.boxShadow='';},1200);
  }
