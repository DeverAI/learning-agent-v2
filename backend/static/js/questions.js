    if(_sgMouseUpHandler){document.removeEventListener('mouseup', _sgMouseUpHandler);_sgMouseUpHandler=null}
    if(_sgDblClickHandler && container){container.removeEventListener('dblclick', _sgDblClickHandler);_sgDblClickHandler=null}
