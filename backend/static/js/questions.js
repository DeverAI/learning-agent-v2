  function cmpZoom(factor){
    _cmpScale*=factor; _cmpScale=Math.max(0.3,Math.min(3,_cmpScale)); _cmpApplyTransform();
  }
  function cmpReset(){
    var vp=document.getElementById('cmpViewport');
    var inner=document.getElementById('cmpInner');
    var svg=inner?inner.querySelector('svg'):null;
    if(!vp||!inner||!svg){_cmpScale=1;_cmpX=0;_cmpY=0;_cmpApplyTransform();return}
    var rect=vp.getBoundingClientRect();
    var vb=svg.getAttribute('viewBox');
    if(!vb){_cmpScale=1;_cmpX=0;_cmpY=0;_cmpApplyTransform();return}
    var parts=vb.trim().replace(/,/g,' ').split(/\s+/).filter(function(v){return v!==''});
    if(parts.length!==4){_cmpScale=1;_cmpX=0;_cmpY=0;_cmpApplyTransform();return}
    var minX=parseFloat(parts[0]),minY=parseFloat(parts[1]),vw=parseFloat(parts[2]),vh=parseFloat(parts[3]);
    if(!isFinite(minX)||!isFinite(minY)||!isFinite(vw)||!isFinite(vh)||vw<=0||vh<=0){_cmpScale=1;_cmpX=0;_cmpY=0;_cmpApplyTransform();return}
    var scale=Math.min(rect.width/vw,rect.height/vh)*0.9;
    scale=Math.max(0.3,Math.min(3,scale));
    _cmpScale=scale;
    _cmpX=(rect.width-vw*scale)/2-minX*scale;
    _cmpY=(rect.height-vh*scale)/2-minY*scale;
    _cmpApplyTransform();
  }
  function _cmpApplyTransform(){
    var inner=document.getElementById('cmpInner');
    if(inner) inner.style.transform='translate('+_cmpX+'px,'+_cmpY+'px) scale('+_cmpScale+')';
  }
  function _cmpCleanupPanZoom(){
    var inner=document.getElementById('cmpInner');
    var vp=document.getElementById('cmpViewport');
    if(_cmpState._mousedownHandler && inner) inner.removeEventListener('mousedown', _cmpState._mousedownHandler);
    if(_cmpState._mousemoveHandler) document.removeEventListener('mousemove', _cmpState._mousemoveHandler);
    if(_cmpState._mouseupHandler) document.removeEventListener('mouseup', _cmpState._mouseupHandler);
    if(_cmpState._wheelHandler && vp) vp.removeEventListener('wheel', _cmpState._wheelHandler);
    _cmpState._mousedownHandler=null;
    _cmpState._mousemoveHandler=null;
    _cmpState._mouseupHandler=null;
    _cmpState._wheelHandler=null;
  }
  function _cmpSetupPanZoom(){
    var inner=document.getElementById('cmpInner');
    var vp=document.getElementById('cmpViewport');
    if(!inner||!vp) return;
    _cmpCleanupPanZoom();
    cmpReset();
    _cmpState._mousedownHandler=function(e){
      if(e.button!==0) return;
      e.preventDefault();
      _cmpDragging=true;
      _cmpStartX=e.clientX-_cmpX;
      _cmpStartY=e.clientY-_cmpY;
      inner.style.cursor='grabbing';
    };
    _cmpState._mousemoveHandler=function(e){
      if(!_cmpDragging) return;
      _cmpX=e.clientX-_cmpStartX;
      _cmpY=e.clientY-_cmpStartY;
      _cmpApplyTransform();
    };
    _cmpState._mouseupHandler=function(){_cmpDragging=false;inner.style.cursor='grab';};
    _cmpState._wheelHandler=function(e){
      e.preventDefault();
      cmpZoom(e.deltaY<0?1.1:0.9);
    };
    inner.addEventListener('mousedown', _cmpState._mousedownHandler);
    document.addEventListener('mousemove', _cmpState._mousemoveHandler);
    document.addEventListener('mouseup', _cmpState._mouseupHandler);
    vp.addEventListener('wheel', _cmpState._wheelHandler, {passive:false});
  }
