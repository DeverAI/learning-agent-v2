  function retryAll(){
    var failed=_allQuestions.filter(function(q){return q.status==='error'}).map(function(q){return q.id});
    if(!failed.length){$toast('没有失败题目','error');return}
    $toast('正在重试 '+failed.length+' 题...','ok');
    function next(i){
      if(i>=failed.length){loadQuestions();return}
      window.$API.post('/api/ocr/'+encodeURIComponent(failed[i])+'/retry').then(function(){next(i+1)}).catch(function(){next(i+1)});
    }
    next(0);
  }

