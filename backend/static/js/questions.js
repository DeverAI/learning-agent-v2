  // 结构梳理图按题目隔离的状态：loading、节流、请求取消
  var _sgState = {};
  var _sgStateKeys = []; // LRU 顺序，限制内存增长
  function _sgGetState(id){
    var key = id || (currentDetail && currentDetail.id);
    if(!key) return null;
    if(!_sgState[key]){
      _sgState[key] = {loading:false, lastActionTime:0, abortCtrl:null, autoGenerated:false, autoGenSuccess:false};
      _sgStateKeys.push(key);
      // 最多保留 50 题的状态，避免长时间使用内存持续增长
      while(_sgStateKeys.length > 50){
        var old = _sgStateKeys.shift();
        if(old && old !== key){
          var oldState = _sgState[old];
          if(oldState && oldState.abortCtrl){
            try{ oldState.abortCtrl.abort(); }catch(e){}
          }
          delete _sgState[old];
        }
      }
    }else{
      // 移动到 LRU 尾部
      var idx = _sgStateKeys.indexOf(key);
      if(idx > -1){ _sgStateKeys.splice(idx,1); _sgStateKeys.push(key); }
    }
    return _sgState[key];
  }
  function _sgIsLoading(id){ var s=_sgGetState(id); return !!s && s.loading; }
  function _sgSetLoading(v, id){ var s=_sgGetState(id); if(s) s.loading=v; }
  function _sgThrottle(id){
    var s=_sgGetState(id); if(!s) return false;
    var now=Date.now();
    if(now - s.lastActionTime < 2000){$toast('操作太频繁，请稍后再试','error');return false}
    s.lastActionTime=now; return true;
  }
  function _sgAbort(id){
    var s=_sgGetState(id);
    if(s && s.abortCtrl){
      try{s.abortCtrl.abort();}catch(e){}
      s.abortCtrl = null;
    }
  }
  function _sgNewAbort(id){
    _sgAbort(id);
    var s=_sgGetState(id);
    if(!s) return null;
    var ctrl = new AbortController();
    // P1#2: 结构图操作依赖 AI 调用，后端默认超时较长，前端至少等待 120 秒
    var tid = setTimeout(function(){ try{ctrl.abort();}catch(e){} }, 120000);
    ctrl.signal.addEventListener('abort', function(){ clearTimeout(tid); });
    ctrl._sgTid = tid; // 暴露给 _cleanup，避免成功响应后计时器泄漏
    s.abortCtrl = ctrl;
    return ctrl;
  }
  function _sgFetch(method, url, body, targetId){
    var s = targetId ? _sgGetState(targetId) : null;
    var ctrl = s && s.abortCtrl ? s.abortCtrl : null;
    var signal = ctrl ? ctrl.signal : null;
    var opts = {method:method, headers:{'Content-Type':'application/json','X-Auth-Token':window.$API._authToken||''}, signal:signal};
    if(body !== undefined) opts.body = JSON.stringify(body);
    function _cleanup(){
      if(ctrl && ctrl._sgTid){ clearTimeout(ctrl._sgTid); ctrl._sgTid = null; }
      if(s && s.abortCtrl === ctrl) s.abortCtrl = null;
    }
    return fetch(url, opts).then(function(r){
      if(!r.ok){
        return r.text().then(function(t){
          _cleanup();
          var detail='';
          try{var d=JSON.parse(t);detail=typeof d.detail==='string'?d.detail:(d.message||'');}catch(e){}
          if(detail) throw new Error(detail);
          throw new Error(r.status+' '+r.statusText+': '+(t||'').slice(0,100));
        });
      }
      _cleanup();
      return r.json();
    }).catch(function(e){
      _cleanup();
      throw e;
    });
  }

